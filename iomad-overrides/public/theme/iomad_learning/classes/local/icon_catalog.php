    /**
     * Normalize Moodle's historical core component aliases.
     *
     * @param string|null $component Component name.
     * @return string
     */
    private static function normalize_component(?string $component): string {
        if ($component === null || $component === '' || $component === 'moodle' || $component === 'theme') {
            return 'core';
        }
        return \core_component::normalize_componentname($component);
    }
