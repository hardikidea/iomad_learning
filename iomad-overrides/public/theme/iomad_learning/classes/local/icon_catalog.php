    /**
     * Resolve a Moodle pix icon to a semantic sprite symbol.
     *
     * @param string|null $component Moodle component.
     * @param string $pix Pix icon name.
     * @return string
     */
    public static function resolve(?string $component, string $pix): string {
        $component = self::normalize_component($component);
        $pix = trim($pix, '/');
        $key = $component . ':' . $pix;

        if (isset(self::ICON_OVERRIDES[$key])) {
            return self::ICON_OVERRIDES[$key];
        }
        if (($pix === 'icon' || $pix === 'monologo') && isset(self::PROJECT_COMPONENTS[$component])) {
            return self::PROJECT_COMPONENTS[$component];
        }
        if (($pix === 'icon' || $pix === 'monologo') && isset(self::COMPONENT_ICONS[$component])) {
            return self::COMPONENT_ICONS[$component];
        }

        $search = strtolower(str_replace(['_', '/'], '-', $pix));
        foreach (self::KEYWORD_ICONS as $keyword => $icon) {
            if (str_contains($search, $keyword)) {
                return $icon;
            }
        }

        $type = strstr($component, '_', true);
        $resolved = self::TYPE_FALLBACKS[$type ?: ''] ?? 'activity';
        return svg_icon_library::has($resolved) ? $resolved : 'activity';
    }

    /**
     * Return project component mappings for contract tests and documentation.
     *
     * @return array<string, string>
     */
    public static function project_components(): array {
        return self::PROJECT_COMPONENTS;
    }

    /**
     * Return browser component mappings for activity and plugin image icons.
     *
     * @return array<string, string>
     */
    public static function client_component_map(): array {
        $map = self::COMPONENT_ICONS + self::PROJECT_COMPONENTS;
        foreach (array_keys(\core_component::get_plugin_types()) as $type) {
            foreach (array_keys(\core_component::get_plugin_list($type)) as $name) {
                $component = \core_component::normalize_componentname($type . '_' . $name);
                $map[$component] ??= self::TYPE_FALLBACKS[$type] ?? 'activity';
            }
        }
        ksort($map);
        return $map;
    }

